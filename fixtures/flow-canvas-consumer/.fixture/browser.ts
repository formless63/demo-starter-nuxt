import { expect } from '@playwright/test'
import type { Page } from '@playwright/test'

export async function checkFlowCanvas(page: Page) {
  const primary = page.getByRole('region', { name: 'Primary diagram' })
  const independent = page.getByRole('region', { name: 'Independent diagram' })
  const nodes = primary.getByRole('list', { name: 'Graph nodes' })
  const links = primary.getByRole('list', { name: 'Graph connections' })
  const persistence = page.locator('[data-persistence-status]')
  await expect(primary.locator('[data-flow-surface]')).toHaveAttribute('data-ready', 'true')
  await expect(independent.locator('[data-flow-surface]')).toHaveAttribute('data-ready', 'true')
  await expect(nodes.getByRole('listitem')).toHaveCount(2)
  await expect(nodes).toContainText('Alpha café 🧭')
  await primary.getByLabel('New node label').fill('<script>plain label</script>')
  await primary.getByRole('button', { name: 'Add node', exact: true }).click()
  await expect(nodes.getByRole('listitem')).toHaveCount(3)
  await expect(nodes).toContainText('<script>plain label</script>')
  await expect(primary.locator('script')).toHaveCount(0)
  await expect(independent.getByRole('list', { name: 'Graph nodes' }).getByRole('listitem')).toHaveCount(2)
  await primary.getByLabel('Source node', { exact: true }).selectOption('alpha')
  await primary.getByLabel('Target node', { exact: true }).selectOption('beta')
  await primary.getByRole('button', { name: 'Connect nodes', exact: true }).click()
  await expect(links.getByRole('listitem')).toHaveCount(1)
  await primary.getByRole('button', { name: 'Connect nodes', exact: true }).click()
  await expect(links.getByRole('listitem')).toHaveCount(1)
  await expect(primary.getByRole('status')).toContainText('Connection rejected')
  await primary.getByLabel('Target node', { exact: true }).selectOption('alpha')
  await primary.getByRole('button', { name: 'Connect nodes', exact: true }).click()
  await expect(links.getByRole('listitem')).toHaveCount(1)
  await page.getByLabel('Reject connections by policy').check()
  await primary.getByLabel('Target node', { exact: true }).selectOption('node-1')
  await primary.getByRole('button', { name: 'Connect nodes', exact: true }).click()
  await expect(links.getByRole('listitem')).toHaveCount(1)
  await page.getByLabel('Reject connections by policy').uncheck()

  await page.getByLabel('Reject editor proposals').check()
  await primary.getByRole('button', { name: 'Edit node alpha', exact: true }).click()
  await primary.getByLabel('X position', { exact: true }).fill('400')
  await primary.getByRole('button', { name: 'Apply node changes' }).click()
  await expect(nodes.locator('[data-node-id="alpha"]')).toContainText('x 30, y 50')
  const visual = primary.locator('.vue-flow__node[data-id="n_61_6c_70_68_61"]')
  await expect(visual).toHaveCSS('transform', 'matrix(1, 0, 0, 1, 30, 50)')
  const box = await visual.boundingBox()
  if (!box) throw new Error('Native canvas node must be visible')
  await page.mouse.move(box.x + box.width / 2, box.y + box.height / 2)
  await page.mouse.down(); await page.mouse.move(box.x + box.width / 2 + 90, box.y + box.height / 2 + 40, { steps: 8 }); await page.mouse.up()
  await expect(nodes.locator('[data-node-id="alpha"]')).toContainText('x 30, y 50')
  await expect(visual).toHaveCSS('transform', 'matrix(1, 0, 0, 1, 30, 50)')
  const pane = primary.locator('.vue-flow__transformationpane')
  const beforeViewport = await pane.evaluate(element => getComputedStyle(element).transform)
  const surface = await primary.locator('[data-flow-surface]').boundingBox()
  if (!surface) throw new Error('Canvas viewport must be visible')
  await page.mouse.move(surface.x + surface.width - 30, surface.y + surface.height - 30)
  const beforeProposals = Number(await page.locator('[data-proposals]').getAttribute('data-count'))
  await page.mouse.wheel(0, -250)
  await expect.poll(async () => Number(await page.locator('[data-proposals]').getAttribute('data-count'))).toBeGreaterThan(beforeProposals)
  await expect(pane).toHaveCSS('transform', beforeViewport)
  await expect(primary.locator('[data-accepted-viewport]')).toHaveAttribute('data-zoom', '1')
  await page.getByLabel('Reject editor proposals').uncheck()
  await primary.getByRole('button', { name: 'Edit node alpha', exact: true }).click()
  await primary.getByLabel('Node label', { exact: true }).fill('Renamed')
  await primary.getByLabel('X position', { exact: true }).fill('120')
  await primary.getByLabel('Y position', { exact: true }).fill('80')
  await primary.getByRole('button', { name: 'Apply node changes' }).click()
  await expect(nodes.locator('[data-node-id="alpha"]')).toContainText('Renamed (alpha), x 120, y 80')
  await expect(visual).toHaveCSS('transform', 'matrix(1, 0, 0, 1, 120, 80)')
  // Text Delete remains an input editing key, never a global graph shortcut.
  await primary.getByRole('button', { name: 'Edit node alpha', exact: true }).click()
  await primary.getByLabel('Node label', { exact: true }).press('Delete')
  await expect(nodes.getByRole('listitem')).toHaveCount(3)
  await primary.getByLabel('Node label', { exact: true }).press('Escape')
  await expect(primary.getByRole('form', { name: 'Edit node', exact: true })).toHaveCount(0)
  await expect(primary.getByRole('button', { name: 'Add node', exact: true })).toBeFocused()
  await expect(primary.locator('[data-flow-surface]')).toHaveAttribute('data-ready', 'true')

  await page.getByRole('button', { name: 'Save graph', exact: true }).click()
  await page.getByRole('button', { name: 'Save graph', exact: true }).click()
  await expect(persistence).toHaveText('Saved by the reference application.')
  await expect(page.locator('[data-dirty]')).toHaveText('No unsaved changes')
  await primary.getByRole('button', { name: 'Delete node beta', exact: true }).click()
  await expect(nodes.getByRole('listitem')).toHaveCount(2)
  await expect(links.getByRole('listitem')).toHaveCount(0)
  await expect(primary.getByRole('button', { name: 'Add node', exact: true })).toBeFocused()
  await page.getByLabel('Fail next synthetic saves').check()
  await page.getByRole('button', { name: 'Save graph', exact: true }).click()
  await expect(persistence).toHaveText('Save failed. Unsaved edits preserved.')
  await expect(page.locator('[data-dirty]')).toHaveText('Unsaved changes')
  await page.getByLabel('Fail next synthetic saves').uncheck()
  await page.getByRole('button', { name: 'Load graph', exact: true }).click()
  await primary.getByLabel('New node label').fill('Newer than load')
  await primary.getByRole('button', { name: 'Add node', exact: true }).click()
  await expect(persistence).toHaveText('Stale completion ignored; newer edits preserved.')
  await expect(nodes).toContainText('Newer than load')
  await page.getByRole('button', { name: 'Save graph', exact: true }).click()
  await primary.getByLabel('New node label').fill('Newer than save')
  await primary.getByRole('button', { name: 'Add node', exact: true }).click()
  await expect(persistence).toHaveText('Stale completion ignored; newer edits preserved.')
  await expect(page.locator('[data-dirty]')).toHaveText('Unsaved changes')
  await page.getByRole('button', { name: 'Save graph', exact: true }).click()
  await page.getByRole('button', { name: 'Cancel persistence', exact: true }).click()
  await expect(persistence).toHaveText('Persistence cancelled.')
  await page.getByRole('button', { name: 'Save graph', exact: true }).click()
  await page.getByRole('button', { name: 'Switch record', exact: true }).click()
  await expect(page.locator('[data-record]')).toContainText('record-b')
  await expect(nodes).not.toContainText('Newer than save')
  await expect(nodes.getByRole('listitem')).toHaveCount(2)
  await page.getByRole('button', { name: 'Load graph', exact: true }).click()
  await page.getByRole('button', { name: 'Toggle editor', exact: true }).click()
  await expect(primary).toHaveCount(0)
  await expect(persistence).toHaveText('Editor toggled; pending persistence discarded.')
  await page.getByRole('button', { name: 'Toggle editor', exact: true }).click()
  await expect(primary.locator('[data-flow-surface]')).toHaveAttribute('data-ready', 'true')
  await page.getByRole('button', { name: 'Export JSON', exact: true }).click()
  const exported = await page.getByLabel('Graph JSON', { exact: true }).inputValue()
  expect(JSON.parse(exported).schemaVersion).toBe(1)
  await page.getByLabel('Graph JSON', { exact: true }).fill('{"schemaVersion":2}')
  await page.getByRole('button', { name: 'Import JSON', exact: true }).click()
  await expect(persistence).toHaveText('Invalid graph JSON. Current graph preserved.')
  await expect(nodes.getByRole('listitem')).toHaveCount(2)
  await page.getByLabel('Graph JSON', { exact: true }).fill(exported)
  await page.getByRole('button', { name: 'Import JSON', exact: true }).click()
  await expect(persistence).toHaveText('Imported graph; not yet saved.')
  const viewportBox = await primary.locator('[data-flow-surface]').boundingBox()
  if (!viewportBox) throw new Error('Viewport must be present')
  await page.mouse.move(viewportBox.x + viewportBox.width - 25, viewportBox.y + viewportBox.height - 25)
  await page.mouse.wheel(0, -250)
  await expect.poll(async () => Number(await primary.locator('[data-accepted-viewport]').getAttribute('data-zoom'))).toBeGreaterThan(1)
  // Native handle selectors must never receive arbitrary imported graph IDs.
  const hostileId = 'quote"[bracket]\n🧭'
  const hostile = JSON.parse(exported)
  hostile.nodes[0].id = hostileId
  const vendorId = (value: string) => `n_${Array.from(value, character => character.codePointAt(0)!.toString(16)).join('_')}`
  await page.getByLabel('Graph JSON', { exact: true }).fill(JSON.stringify(hostile))
  await page.getByRole('button', { name: 'Import JSON', exact: true }).click()
  await expect(primary.locator('[data-flow-surface]')).toHaveAttribute('data-ready', 'true')
  const hostileNode = primary.locator(`.vue-flow__node[data-id="${vendorId(hostileId)}"]`)
  await expect(hostileNode).toBeVisible()
  const out = await hostileNode.locator('.vue-flow__handle.source').boundingBox()
  const incoming = await primary.locator(`.vue-flow__node[data-id="${vendorId('beta')}"] .vue-flow__handle.target`).boundingBox()
  if (!out || !incoming) throw new Error('Native fixed handles must be visible')
  await page.mouse.move(out.x + out.width / 2, out.y + out.height / 2)
  await page.mouse.down()
  await page.mouse.move(incoming.x + incoming.width / 2, incoming.y + incoming.height / 2, { steps: 12 })
  await page.mouse.up()
  await expect(links.getByRole('listitem')).toHaveCount(1)
  await page.getByRole('button', { name: 'Export JSON', exact: true }).click()
  const connected = JSON.parse(await page.getByLabel('Graph JSON', { exact: true }).inputValue())
  expect(connected.edges[0].source).toBe(hostileId)
  expect(connected.edges[0].target).toBe('beta')
  // Pointer movement is accepted through proposals; Escape kills the old drag.
  const drag = await hostileNode.boundingBox()
  if (!drag) throw new Error('Native draggable node must be visible')
  await page.mouse.move(drag.x + drag.width / 2, drag.y + drag.height / 2)
  await page.mouse.down()
  await page.mouse.move(drag.x + drag.width / 2 + 50, drag.y + drag.height / 2 + 20, { steps: 8 })
  await page.keyboard.press('Escape')
  const afterEscape = await nodes.textContent()
  await page.mouse.move(drag.x + drag.width / 2 + 140, drag.y + drag.height / 2 + 90, { steps: 8 })
  await page.mouse.up()
  await expect(nodes).toHaveText(afterEscape ?? '')
  await page.getByLabel('Graph JSON', { exact: true }).fill(exported)
  await page.getByRole('button', { name: 'Import JSON', exact: true }).click()
  await page.getByLabel('Read only', { exact: true }).check()
  await expect(primary.getByRole('button', { name: 'Add node', exact: true })).toBeDisabled()
  await expect(primary.getByRole('button', { name: 'Edit node alpha', exact: true })).toBeDisabled()
  await expect(primary.getByRole('button', { name: 'Delete node alpha', exact: true })).toBeDisabled()
  await expect(page.getByRole('button', { name: 'Import JSON', exact: true })).toBeDisabled()
  await expect(page.getByRole('button', { name: 'Save graph', exact: true })).toBeDisabled()
  await expect(independent.getByRole('button', { name: 'Add node', exact: true })).toBeEnabled()
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await expect(primary.locator('.vue-flow__node').first()).toHaveCSS('animation-name', 'none')
}
