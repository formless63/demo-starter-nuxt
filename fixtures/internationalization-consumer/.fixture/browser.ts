import { expect, type Page } from '@playwright/test'
export async function verifyInternationalization(page: Page) {
  const scope = page.locator('[data-i18n-scope]')
  await expect(scope).toHaveAttribute('lang', 'en')
  await expect(page.getByRole('heading', { name: 'Hello Ada' })).toBeVisible()
  await expect(page.locator('[data-malicious]')).toHaveText('<img src=x onerror=alert(1)>')
  await expect(scope.locator('img,script')).toHaveCount(0)
  await expect(page.locator('[data-missing]')).toHaveText('missing.key')
  await page.getByRole('button', { name: 'de', exact: true }).click()
  await expect(scope).toHaveAttribute('lang', 'de')
  await expect(page).toHaveURL(/locale=de/)
  await expect(page.locator('[data-fallback]')).toHaveText('English fallback')
  await page.getByRole('button', { name: 'ar', exact: true }).click()
  await expect(scope).toHaveAttribute('dir', 'rtl')
  for (const [count, text] of [[0, 'صفر'], [1, 'واحد'], [2, 'اثنان'], [3, '3 قليل'], [11, '11 كثير'], [100, '100 آخر']] as const) await expect(page.locator(`[data-count="${count}"]`)).toHaveText(text)
  await page.goBack()
  await expect(scope).toHaveAttribute('lang', 'de')
  await page.getByLabel('Slow loader').check()
  await page.getByRole('button', { name: 'ar', exact: true }).click()
  await expect(page.getByRole('status')).toHaveText('loading')
  await page.getByRole('button', { name: 'Cancel locale change' }).click()
  await page.waitForTimeout(800)
  await expect(scope).toHaveAttribute('lang', 'de')
  await expect(page).toHaveURL(/locale=de/)
  await page.getByRole('button', { name: 'ar', exact: true }).click()
  await page.getByRole('button', { name: 'en', exact: true }).click()
  await expect(scope).toHaveAttribute('lang', 'en')
  await page.waitForTimeout(800)
  await expect(scope).toHaveAttribute('lang', 'en')
  await page.getByLabel('Fail loader').check()
  await page.getByRole('button', { name: 'ar', exact: true }).click()
  await expect(page.getByRole('status')).toHaveText('error')
  await expect(scope).toHaveAttribute('lang', 'en')
  await expect(page).toHaveURL(/locale=en/)
  await page.getByLabel('Fail loader').uncheck()
  await page.getByLabel('Invalid catalog').check()
  await page.getByRole('button', { name: 'de', exact: true }).click()
  await expect(page.getByRole('status')).toHaveText('error')
  await expect(scope).toHaveAttribute('lang', 'en')
  await page.getByLabel('Invalid catalog').uncheck()
  await page.getByRole('button', { name: 'ar', exact: true }).click()
  await page.goBack()
  await expect(scope).toHaveAttribute('lang', 'de')
  await page.waitForTimeout(800)
  await expect(scope).toHaveAttribute('lang', 'de')
  await expect(page).toHaveURL(/locale=de/)
  await page.getByLabel('Slow loader').uncheck()
  await page.getByRole('button', { name: 'ar', exact: true }).click()
  await expect(scope).toHaveAttribute('lang', 'ar')
  await expect(page).toHaveURL(/locale=ar/)
  await page.getByLabel('Fail loader').check()
  await page.goBack()
  await expect(page.getByRole('status')).toHaveText('error')
  await expect(scope).toHaveAttribute('lang', 'ar')
  await expect(page).toHaveURL(/locale=ar/)
  await page.getByLabel('Fail loader').uncheck()
  await page.getByLabel('Invalid catalog').check()
  await page.goBack()
  await expect(page.getByRole('status')).toHaveText('error')
  await expect(scope).toHaveAttribute('lang', 'ar')
  await expect(page).toHaveURL(/locale=ar/)
  await page.getByLabel('Invalid catalog').uncheck()
  await page.getByLabel('Slow loader').check()
  await page.goBack()
  await expect(page.getByRole('status')).toHaveText('loading')
  await expect(page.getByRole('status')).toHaveText('loading')
  await page.getByRole('button', { name: 'Cancel locale change' }).click()
  await page.waitForTimeout(800)
  await expect(scope).toHaveAttribute('lang', 'ar')
  await expect(page).toHaveURL(/locale=ar/)
  await page.getByLabel('Slow loader').uncheck()
  await page.goBack()
  await expect(scope).toHaveAttribute('lang', 'de')
  await page.goForward()
  await expect(scope).toHaveAttribute('lang', 'ar')
  await expect(page).toHaveURL(/locale=ar/)

  // A deliberately held native request proves Back wins over an ignored-abort completion.
  let release!: () => void
  let sawRequest!: () => void
  const held = new Promise<void>(resolve => { release = resolve })
  const requested = new Promise<void>(resolve => { sawRequest = resolve })
  await page.route('**/api/i18n-reference?*', async route => {
    if (new URL(route.request().url()).searchParams.get('locale') !== 'en') { await route.continue(); return }
    const response = await route.fetch()
    sawRequest()
    await held
    await route.fulfill({ response })
  })
  try {
    await page.getByRole('button', { name: 'en', exact: true }).click()
    await requested
    await expect(scope).toHaveAttribute('lang', 'ar')
    await page.goBack()
    await expect(scope).toHaveAttribute('lang', 'de')
    await expect(page).toHaveURL(/locale=de/)
    const lateResponse = page.waitForResponse(response => new URL(response.url()).searchParams.get('locale') === 'en')
    release()
    await (await lateResponse).finished()
    await page.evaluate(() => new Promise<void>(resolve => requestAnimationFrame(() => requestAnimationFrame(() => resolve()))))
    await expect(page.getByRole('status')).toHaveText('idle')
    await expect(scope).toHaveAttribute('lang', 'de')
    await expect(page).toHaveURL(/locale=de/)
  } finally { release(); await page.unroute('**/api/i18n-reference?*') }

}
